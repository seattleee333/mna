_HJ = None


def hj():
    global _HJ
    if _HJ is None:
        try:
            _HJ = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "hanja_map.json"), encoding="utf-8"))
        except Exception:
            _HJ = {}
    return _HJ


def read_hanja(s):
    m = hj()
    return "".join(m.get(ch, ch) for ch in s)


def tidy(s):
    s = re.sub(r"\s+", " ", s)
    s = re.sub(r"\s*([()（）,·])\s*", r"\1", s)
    s = s.replace("（", "(").replace("）", ")").replace("()", "")
    s = re.sub(r"\(\s*\)", "", s)
    # 조사 앞 띄어쓰기 없애기, 닫는 괄호 뒤 띄우기
    s = re.sub(r"(?<!\(으)\)(?=[^\s)」·,])", ") ", s)
    s = re.sub(r"\s+(의|과의|와의|을|를|에|에서|로|으로|과|와|이|가)(?=[\s(]|$)", r"\1", s)
    return s.strip(" ・、,")


