def kata2hangul(s):
    s = _KW_RE.sub(lambda m: KATA_WORDS[m.group(0)], s)
    out, i = "", 0
    while i < len(s):
        two = s[i:i + 2]
        if two in _KANA_COMBO:
            out += _KANA_COMBO[two]; i += 2; continue
        ch = s[i]
        if ch in _FINAL:
            out = _add_final(out, _FINAL[ch]) if ch == "ン" or i + 1 < len(s) else out
        elif ch == "ー":
            pass
        elif ch in _KANA:
            out += _KANA[ch]
        else:
            out += ch
        i += 1
    return out


