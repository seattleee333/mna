def _batchim(ch):
    return "가" <= ch <= "힣" and (ord(ch) - 0xAC00) % 28 != 0


def _rieul(ch):
    return "가" <= ch <= "힣" and (ord(ch) - 0xAC00) % 28 == 8


def harmonize(t):
    t = re.sub(r"(\S)과의", lambda m: m.group(1) + ("와의" if ("가" <= m.group(1) <= "힣" and not _batchim(m.group(1))) else "과의"), t)
    t = re.sub(r"(\S)\(으\)로", lambda m: m.group(1) + ("으로" if _batchim(m.group(1)) and not _rieul(m.group(1)) else "로"), t)
    t = re.sub(r"([가-힣])를 ", lambda m: m.group(1) + ("을 " if _batchim(m.group(1)) else "를 "), t)
    t = re.sub(r"([가-힣])[과와] ", lambda m: m.group(1) + ("과 " if _batchim(m.group(1)) else "와 "), t)
    return t


_PARTICLE_START = ("의", "과", "와", "를", "에", "로", "가", "는", " ", "(", "·", "")


def jp_ko(title):
    t = title.replace("　", " ")
    # 용어 뒤에 띄어쓰기를 넣어 '연결자회사레카무'처럼 붙지 않게 한다 (조사로 시작하는 말은 앞말에 붙인다)
    t = _JP_RE.sub(lambda m: _JP_MAP[m.group(0)] + ("" if (_JP_MAP[m.group(0)][:1] in _PARTICLE_START or _JP_MAP[m.group(0)].endswith(" ")) else " "), t)
    t = re.sub(r"[ァ-ヴー]+", lambda m: kata2hangul(m.group(0)), t)
    t = re.sub(r"의\s+(주식|지분)", r" \1", t)
    t = re.sub(r"의\s*\(", "(", t)
    t = harmonize(tidy(t.replace("의  ", "의 ")))
    rough = bool(re.search(r"[ぁ-ん]", t))      # 히라가나가 남아 있으면 번역이 덜 된 것
    return t, rough


